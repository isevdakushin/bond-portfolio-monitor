def _fmt(v, unit):
    if unit == "доля":
        return f"{v * 100:g}%"
    return f"{v:g} {unit}"


def columns_table() -> str:
    lines = ["| Колонка | Обязательность | Что содержит | Формат / единицы | Без неё не посчитается | "
             "Распознаваемые названия |", "|---|---|---|---|---|---|"]
    for k in COLUMN_ORDER:
        req, what, fmt, impact = COLUMN_DOCS[k]
        names = ", ".join(PORTFOLIO_COLUMNS[k])
        lines.append(f"| **{COLUMN_LABELS[k]}** | {req} | {what} | {fmt} | {impact} | {names} |")
    return "\n".join(lines)


def thresholds_table(cfg) -> str:
    lines = ["| Допущение | Значение | Обоснование |", "|---|---|---|"]
    for (sec, key), name, unit, why in THRESHOLD_DOCS:
        lines.append(f"| {name} | {_fmt(cfg[sec][key], unit)} | {why} |")
    lines.append("| Лимит HY | сумма целей HY-сегментов листа аллокации (резерв "
                 f"{cfg['concentration']['hy_total_max_fallback'] * 100:g}%) | Из целевой аллокации компании. |")
    return "\n".join(lines)


